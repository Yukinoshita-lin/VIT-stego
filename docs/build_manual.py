    vals = [c[1] for c in cfgs]
    cols = [c[2] for c in cfgs]

    fig, ax = plt.subplots(figsize=(7.4, 4.4), dpi=200)
    bars = ax.barh(names, vals, color=cols, height=0.62)
    for b, v in zip(bars, vals):
        ax.text(v + 0.008, b.get_y() + b.get_height() / 2, '%.4f' % v,
                va='center', ha='left', fontsize=8.5, color='#1a1c1d')
